/**
 * Returns a label resolver for one diagram: the first data key that is present
 * wins; otherwise the built-in default for the active language.
 */
export function diagramLabelResolver(labels: Record<string, string> | undefined, lang: LanguageCode) {
  const data = labels || {};
  const defaults = DIAGRAM_LABELS[lang] ?? DIAGRAM_LABELS.tr;
  return (key: DiagramLabelKey, ...dataKeys: string[]): string => {
    for (const k of dataKeys) {
      const v = data[k];
      if (typeof v === 'string' && v.trim()) return v;
    }
    return defaults[key] ?? DIAGRAM_LABELS.tr[key];
  };
}
